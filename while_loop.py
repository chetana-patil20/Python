#while loop : A while loop is a control flow statement that allows code to be executed repeatedly based on a given Boolean condition. The while loop can be thought of as a repeating if statement. The code inside the loop will continue to execute as long as the condition evaluates to True.

 #loops - repeatedly execute a block of code as long as a condition is true.


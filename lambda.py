#Lambda : A lambda functions are the anonymous functions without a name 
# They can take many arguements but can only have one expression.
#They help keep namespaces clean and are often used as a quick throwaway function.
#It is useful for higher order functions, which take in other functions as arguements like sort(), map(), filter() and reduce().


#Range : A range is generally used in loops to iterate over a sequence of numbers. It generates a sequence of numbers starting from 0 (by default) and increments by 1 (by default) until it reaches a specified number. The range function can take one, two, or three arguments.

#range(start, stop,step) : start is the starting number of the sequence, stop is the end number (exclusive), and step is the difference between each number in the sequence.
nums = range(5) #[0,1,2,3,4]
print(nums)

#1 to 5
range(1,6) #[1,2,3,4,5]